    fn document_of(spec: &ApiSpec) -> Value {
        let operations: Vec<&Operation> = spec.operations.iter().collect();
        schema_document(
            &SchemaContract {
                api: "pets",
                base_url: "https://x/api",
                spec,
                source: json!({"kind": "file"}),
                options: json!([
                    {"name": "TARGET", "short": null, "value": null, "repeatable": false, "help": "the target"},
                    {"name": "--param", "short": "-P", "value": "NAME=VALUE", "repeatable": true, "help": "a parameter"},
                    {"name": "--json", "short": null, "value": null, "repeatable": false, "help": "the envelope"}
                ]),
            },
            &operations,
        )
    }

    fn petstore() -> Value {
        document_of(
            &normalize_spec(
                &serde_json::from_str(include_str!(
                    "../../../tests/fixtures/openapi/petstore.json"
                ))
                .unwrap(),
            )
            .unwrap(),
        )
    }

    fn skill(document: &Value) -> String {
        render_skill(
            document,
            &SkillAuth::OAuth { source: "github" },
            SkillDescriptionSource::File,
        )
    }

    /// A description with `count` operations, each tagged by its tenth.
    fn many(count: usize) -> Value {
        let paths: serde_json::Map<String, Value> = (0..count)
            .map(|index| {
                (
                    format!("/op{index:04}"),
                    json!({"get": {"operationId": format!("op{index:04}"), "summary": "S", "tags": [format!("t{}", index / 10)], "responses": {"200": {"description": "ok"}}}}),
                )
            })
            .collect();
        document_of(
            &normalize_spec(&json!({
                "openapi": "3.0.3",
                "info": {"title": "Many", "version": "1"},
                "paths": paths
            }))
            .unwrap(),
        )
    }

