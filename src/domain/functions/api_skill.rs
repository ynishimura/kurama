//! What `kurama api <API> --skill` prints: an Agent Skill (`SKILL.md`) for
//! one `[api.*]` profile, written from the `--schema` document so the two
//! cannot describe different operations, bounded by `limits::SKILL`.

use std::fmt::Write as _;

use serde_json::Value;

use crate::domain::functions::operation_command::shell_quote;
use crate::domain::types::TokenPlacement;
use crate::domain::types::limits::SKILL;

/// The longest `description` an Agent Skill's frontmatter may hold.
const FRONTMATTER_DESCRIPTION_CHARS: usize = 1024;
/// The longest `name` an Agent Skill's frontmatter may hold.
const FRONTMATTER_NAME_CHARS: usize = 64;
/// Words an Agent Skill's `name` may not contain, and what stands for them.
const RESERVED_NAME_WORDS: [(&str, &str); 2] = [("anthropic", "anth"), ("claude", "cld")];

/// How the profile authenticates, as the configuration says: names only,
/// never a secret reference or a value.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SkillAuth<'a> {
    None,
    OAuth {
        source: &'a str,
    },
    Token {
        source: &'a str,
        placement: &'a TokenPlacement,
    },
    SigV4 {
        aws_profile: &'a str,
        service: Option<&'a str>,
        region: Option<&'a str>,
    },
}

/// Where the description is read from, as the configuration says it (not
/// where this run happened to read it, which would change the Skill from
/// one run to the next).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SkillDescriptionSource {
    File,
    Url { with_credential: bool },
}

/// The `SKILL.md` of the profile the `--schema` `document` describes.
pub fn render_skill(
    document: &Value,
    auth: &SkillAuth,
    description_source: SkillDescriptionSource,
) -> String {
    let raw_api = text(&document["api"]["name"]);
    // `name` where the profile is named, `api` where a command is written.
    let name = one_line(raw_api, SKILL.line_chars);
    let api = shell_quote(&name);
    let api = api.as_str();
    let base_url = text(&document["api"]["base_url"]);
    let description = &document["description"];
    let title = one_line(text(&description["title"]), SKILL.line_chars);
    let version = one_line(text(&description["version"]), SKILL.line_chars);
    let operations = array(&document["operations"]);
    let mut out = String::new();

    let summary = format!(
        "Use when a task calls {title} (version {version}, {count} operations) \
         through the kurama [api.{name}] profile. Build every call with `kurama api {api}` \
         and read an operation's contract with `kurama api {api} --schema OP` first.",
        count = operations.len(),
    );
    // A loader may read `<...>` in the frontmatter as markup.
    let summary = summary.replace(['<', '>'], "");
    out.push_str("---\n");
    let _ = writeln!(out, "name: {}", skill_name(raw_api));
    let _ = writeln!(
        out,
        "description: {}",
        yaml_string(&one_line(&summary, FRONTMATTER_DESCRIPTION_CHARS))
    );
    out.push_str("---\n\n");

    let _ = writeln!(out, "# {} {}\n", code(&name), title);
    let about = one_line(text(&description["description"]), SKILL.description_chars);
    if !about.is_empty() {
        let _ = writeln!(out, "About the API: {about}\n");
    }
    let _ = writeln!(
        out,
        "Generated by `kurama api {api} --skill` from the OpenAPI description \
         ({title} {version}); regenerate it when the description changes.\n"
    );

    out.push_str("## Profile\n\n");
    let _ = writeln!(out, "- Base URL: {}", code(&one_line(base_url, 2048)));
    let server = one_line(text(&description["server"]), SKILL.line_chars);
    if !server.is_empty() {
        let _ = writeln!(out, "- Server the description names: {}", code(&server));
    }
    let _ = writeln!(out, "- Authentication: {}", auth_sentence(api, auth));
    let _ = writeln!(
        out,
        "- Description: {}",
        source_sentence(api, description_source)
    );
    let warnings = array(&document["warnings"]).len();
    if warnings > 0 {
        let _ = writeln!(
            out,
            "- The description has {warnings} warnings about what kurama cannot represent: \
             `kurama api {api} --schema --jq .warnings` lists them."
        );
    }
    out.push('\n');

    write_workflow(&mut out, api);
    write_options(&mut out, array(&document["options"]));
    write_operations(&mut out, api, operations);
    out
}

fn write_workflow(out: &mut String, api: &str) {
    let _ = write!(
        out,
        "## How to call it\n\n\
         1. Find the operation: `kurama api {api} --ops QUERY --json` lists the operations \
         whose id, method, path, summary or tag contains QUERY.\n\
         2. Read its contract: `kurama api {api} --schema OP` (parameter and body JSON Schemas, \
         `limitations`) or `kurama api {api} --describe OP --json` (a body skeleton). \
         Do not guess a parameter or a body property.\n\
         3. Preview: `kurama api {api} OP -P name=value --dry-run --json` prints the plan \
         document (the request with credentials masked, `auth`, the description source, \
         `effects`) and sends nothing.\n\
         4. Call: `kurama api {api} OP -P name=value [-d @body.json] --json` prints \
         `{{status, headers, body}}`; `--jq FILTER` filters the body (the envelope with `--json`); `-o PATH` saves a 2xx \
         body byte for byte (not with `--json` / `--jq` outside `--dry-run`).\n\n\
         With `--json` or `--jq`, a failure is one JSON error document on stderr: read \
         `error.code`, `error.category`, `error.retry` and `error.next_actions` instead of \
         parsing text. Without them it is one `error[CODE]: message` line and an optional \
         `hint:` line. Exit 2: fix the arguments (`API_ARGUMENT_INVALID`, \
         `API_PARAMETER_MISSING`, `API_OPERATION_NOT_FOUND` names the closest ids). \
         Exit 3: a person must act; pass the `hint:` on instead of retrying. Exit 4: the \
         API answered outside 2xx (`API_HTTP_ERROR`; with `--json` the envelope is still \
         on stdout). `kurama agent --json` is the machine-readable catalog of the whole CLI.\n\n"
    );
}

fn write_options(out: &mut String, options: &[Value]) {
    out.push_str("## Options of `kurama api`\n\n");
    for option in options {
        let mut usage = String::new();
        if let Some(short) = option["short"].as_str() {
            let _ = write!(usage, "{short}, ");
        }
        usage.push_str(text(&option["name"]));
        if let Some(value) = option["value"].as_str() {
            let _ = write!(usage, " {value}");
        }
        let repeatable = if option["repeatable"] == true {
            " (repeatable)"
        } else {
            ""
        };
        let _ = writeln!(
            out,
            "- {}{repeatable}: {}",
            code(&usage),
            // kurama's own text, not the description's: never cut.
            one_line(text(&option["help"]), usize::MAX)
        );
    }
    out.push('\n');
}

fn write_operations(out: &mut String, api: &str, operations: &[Value]) {
    out.push_str("## Operations\n\n");
    if operations.is_empty() {
        out.push_str("The description has no operations.\n");
        return;
    }
    if operations.len() <= SKILL.detailed_operations {
        for operation in operations {
            write_operation_detail(out, api, operation);
        }
        return;
    }
    let listed = operations.len().min(SKILL.listed_operations);
    let _ = writeln!(
        out,
        "{} operations: too many to detail here. The first {listed} are one line each \
         below; `kurama api {api} --schema OP` gives an operation's whole contract.\n",
        operations.len()
    );
    write_tags(out, api, operations);
    for operation in &operations[..listed] {
        let _ = writeln!(out, "- {}", operation_line(operation));
    }
    if operations.len() > listed {
        let _ = writeln!(
            out,
            "- ... and {} more: `kurama api {api} --ops QUERY` searches them all.",
            operations.len() - listed
        );
    }
}

/// Every tag with its operation count, alphabetically.
fn write_tags(out: &mut String, api: &str, operations: &[Value]) {
    let mut counts = std::collections::BTreeMap::<String, usize>::new();
    for operation in operations {
        for tag in array(&operation["tags"]) {
            *counts
                .entry(one_line(text(tag), SKILL.line_chars))
                .or_default() += 1;
        }
    }
    if counts.is_empty() {
        return;
    }
    let _ = writeln!(
        out,
        "Tags (`kurama api {api} --ops TAG` lists the operations whose tag, id, path or \
         summary contains TAG):\n"
    );
    for (tag, count) in counts.iter().take(SKILL.listed_operations) {
        let _ = writeln!(out, "- {}: {count}", code(tag));
    }
    if counts.len() > SKILL.listed_operations {
        let _ = writeln!(
            out,
            "- ... and {} more tags",
            counts.len() - SKILL.listed_operations
        );
    }
    out.push_str("\nOperations, in the description's order:\n\n");
}

fn operation_line(operation: &Value) -> String {
    let mut line = format!(
        "{} {} {}",
        code(text(&operation["id"])),
        text(&operation["method"]),
        code(text(&operation["path"]))
    );
    let summary = one_line(text(&operation["summary"]), SKILL.line_chars);
    if !summary.is_empty() {
        let _ = write!(line, ": {summary}");
    }
    if operation["deprecated"] == true {
        line.push_str(" (deprecated)");
    }
    line
}

fn write_operation_detail(out: &mut String, api: &str, operation: &Value) {
    let _ = writeln!(out, "### {}\n", operation_line(operation));
    // Behind a label, so no text of the description starts a line.
    let description = one_line(text(&operation["description"]), SKILL.line_chars);
    if !description.is_empty() {
        let _ = writeln!(out, "About: {description}\n");
    }
    let parameters: Vec<String> = array(&operation["parameters"])
        .iter()
        .map(|parameter| {
            let schema = &parameter["schema"];
            let mut facts = vec![text(&parameter["in"]).to_owned(), type_label(schema)];
            let values = array(&schema["enum"]);
            if !values.is_empty() {
                let mut shown: Vec<String> = values
                    .iter()
                    .take(SKILL.enum_values)
                    .map(|value| code(&value_text(value)))
                    .collect();
                if values.len() > SKILL.enum_values {
                    shown.push(format!("{} more", values.len() - SKILL.enum_values));
                }
                facts.push(format!("one of {}", shown.join(" ")));
            }
            if !schema["default"].is_null() {
                facts.push(format!("default {}", code(&value_text(&schema["default"]))));
            }
            if parameter["required"] == true {
                facts.push("required".into());
            }
            format!("{} ({})", code(text(&parameter["name"])), facts.join(", "))
        })
        .collect();
    if !parameters.is_empty() {
        let _ = writeln!(
            out,
            "- Parameters (`-P name=value`): {}",
            parameters.join(", ")
        );
    }
    let body = &operation["request_body"];
    if !body.is_null() {
        let required = if body["required"] == true {
            "required"
        } else {
            "optional"
        };
        let _ = writeln!(
            out,
            "- Body (`-d`, {required}): {} {}{}",
            text(&body["content_type"]),
            type_label(&body["schema"]),
            properties_label(&body["schema"])
        );
    }
    let response = &operation["response"];
    if !response.is_null() {
        let _ = writeln!(
            out,
            "- Response {}: {} {}{}",
            text(&response["status"]),
            text(&response["content_type"]),
            type_label(&response["schema"]),
            properties_label(&response["schema"])
        );
    }
    let scopes = array(&operation["scopes"]);
    if !scopes.is_empty() {
        let scopes: Vec<String> = scopes.iter().map(|scope| code(text(scope))).collect();
        let _ = writeln!(out, "- Scopes: {}", scopes.join(", "));
    }
    let limitations = array(&operation["limitations"]).len();
    if limitations > 0 {
        let _ = writeln!(
            out,
            "- Limitations: {limitations} ({} lists them)",
            code(&format!(
                "kurama api {api} --schema {}",
                shell_quote(text(&operation["id"]))
            ))
        );
    }
    let _ = writeln!(out, "- Example: {}\n", code(&example(operation)));
}

/// The `--schema` example command, with a required parameter's first enum
/// value or its default in place of the `<name>` placeholder.
fn example(operation: &Value) -> String {
    let mut command = text(&operation["example_command"]).to_owned();
    for parameter in array(&operation["parameters"]) {
        let schema = &parameter["schema"];
        let value = match (array(&schema["enum"]).first(), &schema["default"]) {
            (Some(value), _) => value,
            (None, Value::Null) => continue,
            (None, default) => default,
        };
        let name = text(&parameter["name"]);
        command = command.replace(
            &shell_quote(&format!("{name}=<{name}>")),
            &shell_quote(&format!("{name}={}", value_text(value))),
        );
    }
    command
}

/// A JSON value as a person types it: a string without its quotes.
fn value_text(value: &Value) -> String {
    match value {
        Value::String(text) => one_line(text, SKILL.line_chars),
        other => one_line(&other.to_string(), SKILL.line_chars),
    }
}

/// The type of a `--schema` JSON Schema, in a few words.
fn type_label(schema: &Value) -> String {
    if schema["$ref"].is_string() {
        return "(a schema outside the description)".into();
    }
    let type_name = match &schema["type"] {
        Value::String(name) => name.clone(),
        Value::Array(names) => names.iter().map(text).collect::<Vec<_>>().join(" | "),
        _ => "any".into(),
    };
    if type_name == "array" {
        return format!("array of {}", type_label(&schema["items"]));
    }
    one_line(&type_name, SKILL.line_chars)
}

/// The top-level properties of an object schema, required ones marked.
fn properties_label(schema: &Value) -> String {
    let Some(properties) = schema["properties"].as_object() else {
        return String::new();
    };
    let required = array(&schema["required"]);
    let names: Vec<String> = properties
        .keys()
        .map(|name| {
            if required.iter().any(|value| value == name) {
                format!("{name}*")
            } else {
                name.clone()
            }
        })
        .collect();
    let legend = if required.is_empty() {
        ""
    } else {
        " (* required)"
    };
    format!(
        " with {}{legend}",
        one_line(&names.join(", "), SKILL.line_chars)
    )
}

fn auth_sentence(api: &str, auth: &SkillAuth) -> String {
    match auth {
        SkillAuth::None => "none; requests are sent without a credential.".into(),
        SkillAuth::OAuth { source } => format!(
            "the bearer token of the OAuth source {source}; kurama gets and refreshes it and \
             retries once after a 401. Without a usable token and without a terminal a call \
             exits 3 with {hint}: give that to the person.",
            source = code(&format!("[auth.{source}]")),
            hint = code(&format!("hint: run `kurama login {source}`")),
        ),
        SkillAuth::Token { source, placement } => format!(
            "the credential of {source} {place}, read from its secret store on every call; a \
             401 is the answer, nothing is retried.",
            source = code(&format!("[auth.{source}]")),
            place = match placement {
                TokenPlacement::Header { name, .. } => format!("in the {} header", code(name)),
                TokenPlacement::Basic { .. } => "as the password of HTTP Basic".to_string(),
                TokenPlacement::Query { param } =>
                    format!("in the {} query parameter", code(param)),
            },
        ),
        SkillAuth::SigV4 {
            aws_profile,
            service,
            region,
        } => {
            let mut sentence = format!(
                "a SigV4 signature with the role credentials of the AWS profile {}",
                code(aws_profile)
            );
            if let Some(service) = service {
                let _ = write!(sentence, ", service {}", code(service));
            }
            if let Some(region) = region {
                let _ = write!(sentence, ", region {}", code(region));
            }
            let _ = write!(
                sentence,
                "; `kurama api {api} OP --service NAME --region REGION` overrides the signing \
                 target. A rejected signature is not retried."
            );
            sentence
        }
    }
}

fn source_sentence(api: &str, source: SkillDescriptionSource) -> String {
    match source {
        SkillDescriptionSource::File => {
            "a local file, reread on every use; nothing is fetched.".into()
        }
        SkillDescriptionSource::Url { with_credential } => {
            let credential = if with_credential {
                " with the API's credential (`openapi_auth`)"
            } else {
                " without a credential"
            };
            format!(
                "a URL, fetched{credential} and cached; `kurama api {api} --refresh-spec` \
                 fetches it again."
            )
        }
    }
}

/// The frontmatter `name`: `kurama-api-` and the profile name in lowercase
/// letters, digits and single hyphens, without a reserved word. A name that
/// had to change (or was cut, or is left empty) ends in a hash of the
/// profile name, so two profiles never share a Skill name.
fn skill_name(api: &str) -> String {
    const PREFIX: &str = "kurama-api-";
    let mut slug = String::new();
    for c in api.chars().flat_map(char::to_lowercase) {
        if c.is_ascii_lowercase() || c.is_ascii_digit() {
            slug.push(c);
        } else if !slug.is_empty() && !slug.ends_with('-') {
            slug.push('-');
        }
    }
    let mut slug = slug.trim_end_matches('-').to_owned();
    while let Some((word, stand_in)) = RESERVED_NAME_WORDS
        .iter()
        .find(|(word, _)| slug.contains(word))
    {
        slug = slug.replace(word, stand_in);
    }
    if slug == api && PREFIX.len() + slug.len() <= FRONTMATTER_NAME_CHARS {
        return format!("{PREFIX}{slug}");
    }
    let hash = name_hash(api);
    let room = FRONTMATTER_NAME_CHARS - PREFIX.len() - hash.len() - 1;
    let cut: String = slug.chars().take(room).collect();
    match cut.trim_end_matches('-') {
        "" => format!("{PREFIX}{hash}"),
        cut => format!("{PREFIX}{cut}-{hash}"),
    }
}

/// FNV-1a of `text`, as eight hex digits: stable across runs and builds.
fn name_hash(text: &str) -> String {
    let hash = text.bytes().fold(0x811c_9dc5_u32, |hash, byte| {
        (hash ^ u32::from(byte)).wrapping_mul(0x0100_0193)
    });
    format!("{hash:08x}")
}

/// A YAML double-quoted scalar of a line that holds no control character.
fn yaml_string(line: &str) -> String {
    format!("\"{}\"", line.replace('\\', "\\\\").replace('"', "\\\""))
}

/// `text` on one line: every run of whitespace or control characters is
/// one space, and past `max` characters it ends in `...`.
fn one_line(text: &str, max: usize) -> String {
    let words: Vec<&str> = text
        .split(|c: char| c.is_whitespace() || c.is_control())
        .filter(|word| !word.is_empty())
        .collect();
    let line = words.join(" ");
    if line.chars().count() <= max {
        return line;
    }
    let mut cut: String = line.chars().take(max.saturating_sub(3)).collect();
    cut.push_str("...");
    cut
}

/// A Markdown code span that holds `text` whatever backticks it contains.
fn code(text: &str) -> String {
    let text = one_line(text, 2048);
    let longest = text
        .split(|c| c != '`')
        .map(str::len)
        .max()
        .unwrap_or_default();
    let fence = "`".repeat(longest + 1);
    let pad = if text.starts_with('`') || text.ends_with('`') {
        " "
    } else {
        ""
    };
    format!("{fence}{pad}{text}{pad}{fence}")
}

fn text(value: &Value) -> &str {
    value.as_str().unwrap_or_default()
}

fn array(value: &Value) -> &[Value] {
    value.as_array().map(Vec::as_slice).unwrap_or_default()
}

