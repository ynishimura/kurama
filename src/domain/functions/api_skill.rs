    #[test]
    fn names_and_lines_are_cut_to_what_the_format_allows() {
        assert_eq!(skill_name("github"), "kurama-api-github");
        assert_eq!(skill_name("billing-api-dev"), "kurama-api-billing-api-dev");
        let changed = skill_name("GitHub_Prod.v2");
        assert_eq!(
            changed,
            format!("kurama-api-github-prod-v2-{}", name_hash("GitHub_Prod.v2"))
        );
        assert_ne!(
            changed,
            skill_name("github-prod-v2"),
            "a changed name keeps its own hash"
        );
        let japanese = skill_name("日本");
        assert_eq!(japanese, format!("kurama-api-{}", name_hash("日本")));
        assert_ne!(japanese, skill_name("中国"));
        let reserved = skill_name("claude-anthropic");
        assert!(reserved.starts_with("kurama-api-cld-anth-"), "{reserved}");
        assert!(!reserved.contains("claude") && !reserved.contains("anthropic"));
        let long = skill_name(&"a".repeat(100));
        assert_eq!(long.len(), FRONTMATTER_NAME_CHARS);
        assert!(long.ends_with(&name_hash(&"a".repeat(100))));
        assert_eq!(
            skill_name(&"a".repeat(53)),
            format!("kurama-api-{}", "a".repeat(53))
        );
        assert_ne!(
            skill_name(&"a".repeat(54)),
            format!("kurama-api-{}", "a".repeat(54))
        );
        assert_eq!(
            skill_name("x-"),
            format!("kurama-api-x-{}", name_hash("x-"))
        );
        for name in [changed, japanese, reserved, long] {
            assert!(name.len() <= FRONTMATTER_NAME_CHARS);
            assert!(
                name.chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'),
                "{name}"
            );
            assert!(!name.contains("--") && !name.ends_with('-'), "{name}");
        }
        assert_eq!(name_hash(""), "811c9dc5");
        assert_eq!(one_line(" a \n\t b\u{7}c ", 10), "a b c");
        assert_eq!(one_line("abcdef", 5), "ab...");
        assert_eq!(one_line("abcde", 5), "abcde");
        assert_eq!(code("x"), "`x`");
        assert_eq!(code("`x"), "`` `x ``");
        assert_eq!(yaml_string("a\"b\\c"), "\"a\\\"b\\\\c\"");
    }

    #[test]
    fn no_description_text_starts_a_line_of_markdown() {
        let mut document = petstore();
        for (index, text) in ["~~~ fence", "<!-- hidden", "# heading", "---"]
            .iter()
            .enumerate()
        {
            document["operations"][index]["description"] = json!(format!("{text}\n\n{text}"));
        }
        document["operations"][4]["summary"] = json!("<b>bold</b>");
        document["description"]["title"] = json!("<Pets> & <script>");
        let skill = skill(&document);
        for line in skill.lines().skip(4) {
            for opener in ["~~~", "<!--", "# heading", "---", "<b>", "<Pets>"] {
                assert!(!line.starts_with(opener), "{line:?} starts with {opener}");
            }
        }
        assert!(skill.contains("\nAbout: ~~~ fence ~~~ fence\n"));
        assert!(skill.contains("\nAbout: <!-- hidden <!-- hidden\n"));
        let frontmatter = skill.lines().nth(2).unwrap();
        assert!(
            !frontmatter.contains('<') && !frontmatter.contains('>'),
            "{frontmatter}"
        );
        assert!(
            frontmatter.contains("calls Pets & script (version"),
            "{frontmatter}"
        );
    }

